// JavaScript 문장과 코드 블록의 기본 형태
const itemName = "keyboard";
const itemPrice = 45000;

console.log(itemName); // keyboard
console.log(itemPrice); // 45000

// 여러 문장을 중괄호로 묶어 코드 블록을 만들 수 있다.
if (itemPrice < 50000) {
  console.log("예산 안에 들어옵니다."); // 예산 안에 들어옵니다.
}

